import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { declareDiscoveryExtension, validateDiscoveryExtension, validateDiscoveryExtensionSpec } from "@x402/extensions/bazaar";

const config = JSON.parse(await readFile(new URL("../discovery-config.json", import.meta.url), "utf8"));
const generated = declareDiscoveryExtension(config);
for (const validate of [validateDiscoveryExtensionSpec, validateDiscoveryExtension]) {
  const result = validate(generated.bazaar);
  assert.equal(result.valid, true, JSON.stringify(result.errors));
}
const start = "// BEGIN SDK-GENERATED BAZAAR";
const end = "// END SDK-GENERATED BAZAAR";
const workerUrl = new URL("../worker.js", import.meta.url);
const source = await readFile(workerUrl, "utf8");
assert.equal(source.split(start).length, 2, "expected one generated-block start");
assert.equal(source.split(end).length, 2, "expected one generated-block end");
const from = source.indexOf(start);
const to = source.indexOf(end) + end.length;
assert.ok(from < to);
const block = `${start}\n// Generated by @x402/extensions 2.31.0; edit discovery-config.json, not this block.\nconst BAZAAR_EXTENSION = ${JSON.stringify(generated, null, 2)};\n${end}`;
const expected = source.slice(0, from) + block + source.slice(to);
const args = process.argv.slice(2);
assert.ok(args.length === 0 || (args.length === 1 && args[0] === "--check"), "usage: node generate-discovery.mjs [--check]");
if (args[0] === "--check") {
  assert.equal(source, expected, "discovery block differs from the pinned SDK output; run npm run generate");
  console.log("SDK_GENERATED_DISCOVERY_MATCH=true; no network or deployment");
} else {
  await writeFile(workerUrl, expected, "utf8");
  console.log("SDK_GENERATED_DISCOVERY_WRITTEN; source only, no deployment");
}
