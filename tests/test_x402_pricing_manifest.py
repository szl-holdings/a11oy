"""The served x402 price manifest, the /pricing per-call table and the image COPY agree.

`.well-known/x402-pricing.json` and the generated region of `pages/pricing.html` both
come from szl-gov `tools/pricing_catalog.py`, which renders them from
`pricing/catalog.yaml` (the canonical per-call catalog, itself checked against the
exported Cloudflare Monetization Gateway rules). Neither is edited by hand here, so
these tests bind the two copies to each other and to the runtime image.
"""
from decimal import Decimal
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / ".well-known" / "x402-pricing.json"
PRICING = ROOT / "pages" / "pricing.html"
BEGIN = ("<!-- szl:x402-per-call:begin generated by szl-gov tools/pricing_catalog.py "
         "from pricing/catalog.yaml sha256=")
END = "<!-- szl:x402-per-call:end -->"


def manifest() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def generated_region() -> str:
    page = PRICING.read_text(encoding="utf-8")
    assert page.count(BEGIN) == 1 and page.count(END) == 1
    return page[page.index(BEGIN):page.index(END) + len(END)]


def test_manifest_is_the_generated_document_without_the_old_claims() -> None:
    m = manifest()
    assert m["schema"] == "szl.x402-pricing/v2"
    assert (m["protocol"], m["x402_version"]) == ("x402", 2)
    # The hand-written predecessor claimed to mirror the live rules while
    # misstating them; the generated file carries its source instead.
    assert "honesty_note" not in m and "monetization_gateway_note" not in m
    assert re.fullmatch(r"[0-9a-f]{64}", m["source"]["catalog_sha256"])
    assert m["source"]["catalog"] == "https://github.com/szl-holdings/szl-gov/blob/main/pricing/catalog.yaml"
    assert m["payment"]["network"] == "eip155:8453"
    assert m["payment"]["atomic_per_usd"] == 1_000_000


def test_every_listed_price_is_internally_consistent() -> None:
    m = manifest()
    assert m["paid_surfaces"]
    for surface in m["paid_surfaces"]:
        atomic = int(surface["amount_atomic"])
        assert 1_000 <= atomic <= 100_000_000  # the gateway's $0.001 .. $100 range
        assert Decimal(surface["price_usd"]) * m["payment"]["atomic_per_usd"] == atomic
        assert surface["path_prefixes"] and all(p.startswith("/") for p in surface["path_prefixes"])
        assert surface["audience"] in {"everyone", "verified_bots"}
        assert re.fullmatch(r"[0-9a-f]{32}", surface["rule_id"])
    for surface in m["not_offered_yet"]:
        assert surface["status"] == "not offered yet"
        assert "price_usd" not in surface and "amount_atomic" not in surface


def test_rule_counts_add_up() -> None:
    m = manifest()
    counts = m["rule_counts"]
    assert counts["rules_defined"] == sum(z["rules_defined"] for z in counts["zones"])
    assert counts["rules_enabled"] == sum(z["rules_enabled"] for z in counts["zones"])
    assert counts["rules_enabled"] == len(m["paid_surfaces"])


def test_the_manifest_and_the_pricing_page_are_listed_free() -> None:
    free = [url for group in manifest()["free_surfaces"] for url in group["examples"]]
    assert "https://a-11-oy.com/.well-known/x402-pricing.json" in free
    assert "https://a-11-oy.com/pricing" in free


def test_pricing_page_table_comes_from_the_same_catalog() -> None:
    m = manifest()
    region = generated_region()
    assert region[len(BEGIN):len(BEGIN) + 64] == m["source"]["catalog_sha256"]
    charged = re.findall(
        r'<tr data-entry-id="([^"]+)" data-rule-id="([0-9a-f]{32})" data-amount-atomic="(\d+)">', region)
    assert charged == [(s["id"], s["rule_id"], s["amount_atomic"]) for s in m["paid_surfaces"]]
    for surface in m["paid_surfaces"]:
        assert f'${surface["price_usd"]} USDC ({surface["amount_atomic"]} atomic' in region
    not_offered = re.findall(r'<tr data-entry-id="([^"]+)" data-status="not-offered-yet">', region)
    assert not_offered == [s["id"] for s in m["not_offered_yet"]]
    assert '<a href="/.well-known/x402-pricing.json">' in region


def test_no_per_call_price_outside_the_generated_region() -> None:
    page = PRICING.read_text(encoding="utf-8").replace(generated_region(), "")
    assert re.search(r"\$0\.\d", page) is None
    retired = (ROOT / "console" / "pricing.html").read_text(encoding="utf-8")
    assert re.search(r"\$\d", retired) is None
    assert 'href="/pricing"' in retired and "portal.szlholdings.com" not in retired


def test_runtime_image_serves_the_manifest_beside_security_txt() -> None:
    dockerfile = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    assert "COPY .well-known/security.txt .well-known/x402-pricing.json ./static/.well-known/" in dockerfile
